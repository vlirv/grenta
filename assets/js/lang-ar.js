  function translateWords(text) {
    let out = text;
    WORDS.forEach(function (w) { out = out.replace(w[0], w[1]); });
    return out;
  }

  function translate(text) {
    const trimmed = text.replace(/\s+/g, " ").trim();
    if (!trimmed || !/[A-Za-z]/.test(trimmed)) return null;
    if (Object.prototype.hasOwnProperty.call(AR, trimmed)) return AR[trimmed];
    for (let i = 0; i < PATTERNS.length; i++) {
      if (PATTERNS[i][0].test(trimmed)) return trimmed.replace(PATTERNS[i][0], PATTERNS[i][1]);
    }
    const words = translateWords(trimmed);
    return words !== trimmed ? words : null;
  }

  // Do not touch what people typed, codes or e-mails
  function skip(el) {
    return !el || el.closest("script, style, textarea, code, [contenteditable], .no-translate");
  }

  function translateTextNode(node) {
    const el = node.parentElement;
    if (skip(el)) return;
    // <option> without value: keep the English value so filters and forms still work
    if (el.tagName === "OPTION" && !el.hasAttribute("value")) el.setAttribute("value", el.textContent.trim());
    const result = translate(node.nodeValue);
    if (result !== null && result !== node.nodeValue.trim()) {
      const lead = node.nodeValue.match(/^\s*/)[0];
      const tail = node.nodeValue.match(/\s*$/)[0];
      node.nodeValue = lead + result + tail;
    }
  }

  function translateElement(root) {
    if (root.nodeType === 3) { translateTextNode(root); return; }
    if (root.nodeType !== 1 || skip(root)) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(translateTextNode);
    [root].concat(Array.from(root.querySelectorAll("[placeholder], [title], [aria-label]"))).forEach(function (el) {
      ["placeholder", "title", "aria-label"].forEach(function (attr) {
        const value = el.getAttribute && el.getAttribute(attr);
        if (!value) return;
        const result = translate(value);
        if (result !== null && result !== value) el.setAttribute(attr, result);
      });
    });
  }

  function translateTitle() {
    const parts = document.title.split(" | ");
    document.title = parts.map(function (p) { return translate(p) || p; }).join(" | ");
  }

  // Pop-up messages from alert() and confirm()
  const nativeAlert = window.alert.bind(window);
  const nativeConfirm = window.confirm.bind(window);
  window.alert = function (msg) { return nativeAlert(translate(String(msg)) || msg); };
  window.confirm = function (msg) { return nativeConfirm(translate(String(msg)) || msg); };

  function start() {
    translateElement(document.body);
    translateTitle();
    // Text added later by page scripts (cards, tables, alerts…)
    new MutationObserver(function (mutations) {
      mutations.forEach(function (m) {
        if (m.type === "characterData") translateTextNode(m.target);
        m.addedNodes.forEach(translateElement);
        if (m.type === "attributes") translateElement(m.target);
      });
    }).observe(document.body, {
      childList: true, subtree: true, characterData: true,
      attributes: true, attributeFilter: ["placeholder", "title", "aria-label"]
    });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start);
  else start();
